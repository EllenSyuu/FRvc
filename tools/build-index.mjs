// Regenerates data/{vocab,gloss,grammar,reading}/index.js from the files in each folder.
// Run after adding a content file:  node tools/build-index.mjs
import { readdirSync, writeFileSync } from 'node:fs';

const ORDER = {
  vocab: ['corps', 'soins', 'emotions', 'relations', 'sport', 'cuisine', 'mode', 'maison', 'achats', 'voyage',
    'arts', 'lettres', 'histoire', 'engagement', 'medias', 'politique', 'justice', 'economie', 'finances', 'bureau',
    'nature', 'animaux', 'sciences', 'energie', 'mobilite', 'temps', 'espace', 'mesures', 'argumenter', 'quebec'],
};

for (const dir of ['vocab', 'gloss', 'grammar', 'reading']) {
  const path = new URL(`../data/${dir}/`, import.meta.url);
  let files = readdirSync(path).filter(f => f.endsWith('.js') && f !== 'index.js').map(f => f.slice(0, -3));
  const order = ORDER[dir];
  files.sort((a, b) => (order ? (order.indexOf(a) + 1 || 999) - (order.indexOf(b) + 1 || 999) : 0) || a.localeCompare(b, 'en', { numeric: true }));
  const id = f => `m_${f.replace(/[^a-z0-9]/gi, '_')}`;
  const body =
    `// Generated by tools/build-index.mjs — do not edit by hand.\n` +
    files.map(f => `import ${id(f)} from './${f}.js';`).join('\n') +
    `\n\nexport default [${files.map(id).join(', ')}];\n`;
  writeFileSync(new URL('index.js', path), body);
  console.log(dir, files.length);
}
